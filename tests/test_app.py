def test_unregister_then_signup_again(client):
    # Arrange
    activity_name = "Soccer Club"
    email = "student@example.com"
    activities[activity_name]["participants"].append(email)

    # Act
    unregister_response = client.delete(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )
    signup_response = client.post(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )

    # Assert
    assert unregister_response.status_code == 200
    assert signup_response.status_code == 200
    assert activities[activity_name]["participants"] == [email]


def test_participants_are_isolated_between_activities(client):
    # Arrange
    email = "student@example.com"
    first_activity = "Soccer Club"
    second_activity = "Art Club"

    # Act
    response = client.post(
        f"/activities/{first_activity}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 200
    assert email in activities[first_activity]["participants"]
    assert email not in activities[second_activity]["participants"]
